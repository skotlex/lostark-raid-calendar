/**
 * 표에 없는 클래스가 기댈 값.
 *
 * 가장 큰 체형(남성 전사)에 맞춘다. 새 직업이 나왔을 때 머리가 창 위로 잘려 나가는 것보다
 * 머리 위가 조금 빈 편이 낫다. 잘린 얼굴은 누구인지 알 수 없지만 여백은 알아볼 수 있다.
 */
const FALLBACK = BODY.남성전사;

/** 머리 꼭대기의 세로 위치. */
export function headTop(className: string | null | undefined): number {
  if (!className) return FALLBACK;
  return HEAD_TOP[className] ?? FALLBACK;
}

/**
 * 잘라낼 구간이 시작하는 높이.
 *
 * 머리 꼭대기보다 조금 위에서 시작해 정수리가 창에 붙지 않게 한다. 값은 지금까지
 * 버서커 기준으로 쓰던 8.5%를 그대로 재현하는 여백이다(0.099 - 0.015 ≒ 0.085).
 */
export function cropTop(className: string | null | undefined): number {
  return headTop(className) - 0.015;
}

/**
 * 확대 원점. 배경으로 깔리는 초상(PortraitBleed·PortraitCard)이 쓴다.
 *
 * 잘라내는 것이 아니라 한 점을 잡고 키우는 방식이라 머리 꼭대기가 아니라 **얼굴 언저리**를
 * 잡아야 한다. 여기서도 버서커 기준으로 쓰던 14%가 그대로 나온다(0.099 + 0.04).
 */
export function anchorY(className: string | null | undefined): number {
  return headTop(className) + 0.04;
}
